///  * The current alpha value as a number.
///
/// Notes:
///  * Example:
///      `hs.dialog.color.alpha(0.5)`
private func colorPanelAlpha(_ L: LuaState) throws -> CInt {

    let cp = NSColorPanel.shared
    if lua_gettop(L) == 1 {
        let alpha = lua_tovalue(L, at: 1) as! NSNumber
        let color = cp.color.withAlphaComponent(CGFloat(alpha.doubleValue))
        cp.color = color
    }

    L.push(Double(NSColorPanel.shared.alpha))
    return 1
}

