/// hs.dialog.color.color([value]) -> table
/// Function
/// Set or display the currently selected color in a color wheel.
///
/// Parameters:
///  * [value] - The color values in a table (as described in `hs.drawing.color`).
///
/// Returns:
///  * A table of the currently selected color in the form of `hs.drawing.color`.
///
/// Notes:
///  * Example:
///      `hs.dialog.color.color(hs.drawing.color.blue)`
private func colorPanelColor(_ L: LuaState) throws -> CInt {
    let cp = NSColorPanel.shared
    if lua_gettop(L) == 1 {
        guard let theColor = table_toNSColor(L, 1) as? NSColor else {
            throw LuaCallError("bad argument #1 (expected color table)")
        }
        cp.color = theColor
    }
    NSColor_tolua(L, cp.color)
    return 1
}

/// hs.dialog.color.mode([value]) -> table
/// Function
/// Set or display the currently selected color panel mode.
///
/// Parameters:
///  * [value] - The mode you wish to use as a string from the following options:
///    ** "wheel" - Color Wheel
///    ** "gray" - Gray Scale Slider
///    ** "RGB" - RGB Sliders
///    ** "CMYK" - CMYK Sliders
///    ** "HSB" - HSB Sliders
///    ** "list" - Color Palettes
///    ** "custom" - Image Palettes
///    ** "crayon" - Pencils
///    ** "none"
///
/// Returns:
///  * The current mode as a string.
///
/// Notes:
///  * Example:
///      `hs.dialog.color.mode("RGB")`
private func colorPanelMode(_ L: LuaState) throws -> CInt {
    let cp = NSColorPanel.shared
    if lua_gettop(L) == 1 {
        let theMode = lua_tovalue(L, at: 1) as! String
        switch theMode {
        case "none":   cp.mode = .none
        case "gray":   cp.mode = .gray
        case "RGB":    cp.mode = .RGB
        case "CMYK":   cp.mode = .CMYK
        case "HSB":    cp.mode = .HSB
        case "custom": cp.mode = .customPalette
        case "list":   cp.mode = .colorList
        case "wheel":  cp.mode = .wheel
        case "crayon": cp.mode = .crayon
        default:
            throw LuaCallError("unknown color panel mode")
        }
    }

    switch cp.mode {
    case .none:          lua_pushany(L, "none")
    case .gray:          lua_pushany(L, "gray")
    case .RGB:           lua_pushany(L, "RGB")
    case .CMYK:          lua_pushany(L, "CMYK")
    case .HSB:           lua_pushany(L, "HSB")
    case .customPalette: lua_pushany(L, "custom")
    case .colorList:     lua_pushany(L, "list")
    case .wheel:         lua_pushany(L, "wheel")
    case .crayon:        lua_pushany(L, "crayon")
    default:
        lua_pushany(L, "** unrecognized mode:\(cp.mode.rawValue)")
    }
    return 1
}

