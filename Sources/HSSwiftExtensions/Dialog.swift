import Cocoa
import LuaSkin

private let USERDATA_TAG = "hs.dialog"
private var refTable: LSRefTable = LUA_NOREF

// MARK: - Support Functions and Classes

//
// COLOR PANEL:
//
private class HSColorPanel: NSObject {
    var callbackRef: Int32 = LUA_NOREF

    override init() {
        super.init()
        let cp = NSColorPanel.shared
        cp.setTarget(self)
        cp.setAction(#selector(colorCallback(_:)))

        NotificationCenter.default.addObserver(
            self,
            selector: #selector(colorClose(_:)),
            name: NSWindow.willCloseNotification,
            object: cp
        )
    }

    // Second argument to callback is true indicating this is a close color panel event
    @objc func colorClose(_ note: NSNotification) {
        if callbackRef != LUA_NOREF {
            DispatchQueue.main.async { [weak self] in
                guard let self = self, self.callbackRef != LUA_NOREF else { return }
                let skin = LuaSkin.skin(with: nil)
                _lua_stackguard_entry(skin.l)
                let L = skin.l!
                let cp = NSColorPanel.shared
                skin.pushLuaRef(refTable, ref: self.callbackRef)
                skin.pushNSObject(cp.color)
                lua_pushboolean(L, 1)
                skin.protectedCallAndError("hs.dialog color close callback", nargs: 2, nresults: 0)
                _lua_stackguard_exit(skin.l)
            }
        }
    }

    // Second argument to callback is false indicating that the color panel is still open (i.e. they may change color again)
    @objc func colorCallback(_ colorPanel: NSColorPanel) {
        if callbackRef != LUA_NOREF {
            DispatchQueue.main.async { [weak self] in
                guard let self = self, self.callbackRef != LUA_NOREF else { return }
                let skin = LuaSkin.skin(with: nil)
                _lua_stackguard_entry(skin.l)
                let L = skin.l!
                skin.pushLuaRef(refTable, ref: self.callbackRef)
                skin.pushNSObject(colorPanel.color)
                lua_pushboolean(L, 0)
                skin.protectedCallAndError("hs.dialog color callback", nargs: 2, nresults: 0)
                _lua_stackguard_exit(skin.l)
            }
        }
    }
}

private var cpReceiverObject: HSColorPanel?

