// MARK: - Support Functions and Classes

//
// COLOR PANEL:
//
private class HSColorPanel: NSObject {
    var callbackRef: LuaValue?
    var generation: UInt64 = 0
    var observerToken: (any NotificationObserverToken)?
    weak var notificationRef: (any NotificationProtocol)?

    override init() {
        super.init()
        let cp = NSColorPanel.shared
        cp.setTarget(self)
        cp.setAction(#selector(colorCallback(_:)))
    }

    func registerObserver(_ L: UnsafeMutablePointer<lua_State>!) {
        let notif = environmentGet(L).notification
        observerToken = notif.addObserver(name: NSWindow.willCloseNotification.rawValue, object: NSColorPanel.shared) { [weak self] _ in
            self?.colorClose()
        }
        notificationRef = notif
    }

    // Second argument to callback is true indicating this is a close color panel event
    func colorClose() {
        if callbackRef != nil {
            DispatchQueue.main.async { [weak self] in
                guard let self = self, let cb = self.callbackRef else { return }
                guard lua_isStateGenerationValid(self.generation) else { return }
                let L = lua_getCurrentState()!
                let cp = NSColorPanel.shared
                cb.push(onto: L)
                NSColor_tolua(L, cp.color)
                L.push(true)
                if lua_pcall(L, 2, 0, 0) != LUA_OK { lua_pop(L, 1) }
            }
        }
    }

    // Second argument to callback is false indicating that the color panel is still open (i.e. they may change color again)
    @objc func colorCallback(_ colorPanel: NSColorPanel) {
        if callbackRef != nil {
            DispatchQueue.main.async { [weak self] in
                guard let self = self, let cb = self.callbackRef else { return }
                guard lua_isStateGenerationValid(self.generation) else { return }
                let L = lua_getCurrentState()!
                cb.push(onto: L)
                NSColor_tolua(L, colorPanel.color)
                L.push(false)
                if lua_pcall(L, 2, 0, 0) != LUA_OK { lua_pop(L, 1) }
            }
        }
    }
}

private var cpReceiverObject: HSColorPanel?

// MARK: - Color Panel Functions

/// hs.dialog.color.callback([callbackFn]) -> function or nil
/// Function
/// Sets or removes the callback function for the color panel.
///
/// Parameters:
///  * a function, or `nil` to remove the current function, which will be invoked as a callback for messages generated by this color panel. The callback function should expect 2 arguments as follows:
///    ** A table containing the color values from the color panel.
///    ** A boolean which returns `true` if the color panel has been closed otherwise `false` indicating that the color panel is still open (i.e. it may change color again).
///
/// Returns:
///  * The last callbackFn or `nil` so you can save it and re-attach it if something needs to temporarily take the callbacks.
///
/// Notes:
///  * Example:
///      `hs.dialog.color.callback(function(a,b) print("COLOR CALLBACK:\nSelected Color: " .. hs.inspect(a) .. "\nPanel Closed: " .. hs.inspect(b)) end)`
private func colorPanelCallback(_ L: LuaState) throws -> CInt {

    if let cb = cpReceiverObject!.callbackRef {
        cb.push(onto: L)
    } else {
        lua_pushnil(L)
    }
    if lua_gettop(L) == 2 { // we just added to it...
        // in either case, we need to remove an existing callback, so...
        cpReceiverObject!.callbackRef = nil
        if lua_type(L, 1) == LUA_TFUNCTION {
            cpReceiverObject!.callbackRef = L.ref(index: 1)
            cpReceiverObject!.generation = lua_currentStateGeneration()
        }
    }
    // return the *last* fn (or nil) so you can save it and re-attach it if something needs to
    // temporarily take the callbacks
    return 1
}

