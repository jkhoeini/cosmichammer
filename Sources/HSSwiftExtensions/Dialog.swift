/// hs.dialog.color.mode([value]) -> table
/// Function
/// Set or display the currently selected color panel mode.
///
/// Parameters:
///  * [value] - The mode you wish to use as a string from the following options:
///    ** "wheel" - Color Wheel
///    ** "gray" - Gray Scale Slider
///    ** "RGB" - RGB Sliders
///    ** "CMYK" - CMYK Sliders
///    ** "HSB" - HSB Sliders
///    ** "list" - Color Palettes
///    ** "custom" - Image Palettes
///    ** "crayon" - Pencils
///    ** "none"
///
/// Returns:
///  * The current mode as a string.
///
/// Notes:
///  * Example:
///      `hs.dialog.color.mode("RGB")`
private func colorPanelMode(_ L: UnsafeMutablePointer<lua_State>!) -> Int32 {
    let skin = LuaSkin.skin(with: L)
    skin.checkArgs(LS_TSTRING | LS_TOPTIONAL, LS_TBREAK)
    let cp = NSColorPanel.shared
    if lua_gettop(L) == 1 {
        let theMode = skin.toNSObject(atIndex: 1) as! String
        switch theMode {
        case "none":   cp.mode = .none
        case "gray":   cp.mode = .gray
        case "RGB":    cp.mode = .RGB
        case "CMYK":   cp.mode = .CMYK
        case "HSB":    cp.mode = .HSB
        case "custom": cp.mode = .customPalette
        case "list":   cp.mode = .colorList
        case "wheel":  cp.mode = .wheel
        case "crayon": cp.mode = .crayon
        default:
            return luaL_error(L, "unknown color panel mode")
        }
    }

    switch cp.mode {
    case .none:          skin.pushNSObject("none")
    case .gray:          skin.pushNSObject("gray")
    case .RGB:           skin.pushNSObject("RGB")
    case .CMYK:          skin.pushNSObject("CMYK")
    case .HSB:           skin.pushNSObject("HSB")
    case .customPalette: skin.pushNSObject("custom")
    case .colorList:     skin.pushNSObject("list")
    case .wheel:         skin.pushNSObject("wheel")
    case .crayon:        skin.pushNSObject("crayon")
    default:
        skin.pushNSObject("** unrecognized mode:\(cp.mode.rawValue)")
    }
    return 1
}

