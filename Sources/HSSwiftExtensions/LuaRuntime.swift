/// hs.processInfo
/// Constant
/// A table containing read-only information about the Cosmic Hammer application instance currently running.
private func push_hammerAppInfo(_ L: UnsafeMutablePointer<lua_State>!) -> Int32 {
    precondition(L != nil, "Lua state must not be nil")
    let baseTop = lua_gettop(L)
    // Fetch the CPU architecture in use
    var arch = "Unknown"
    var utsname = utsname()
    if uname(&utsname) == 0 {
        arch = withUnsafePointer(to: &utsname.machine) {
            $0.withMemoryRebound(to: CChar.self, capacity: Int(_SYS_NAMELEN)) {
                String(cString: $0)
            }
        }
    }

    let bundle = Bundle.main
    let infoDictionary = bundle.infoDictionary ?? [:]

    #if DEBUG
    let isDebugBuild = true
    #else
    let isDebugBuild = false
    #endif

    let appInfo: [String: Any] = [
        "version": infoDictionary["CFBundleShortVersionString"] as? String ?? "",
        "build": infoDictionary["CFBundleVersion"] as? String ?? "",
        "resourcePath": String(cString: (bundle.resourcePath! as NSString).fileSystemRepresentation),
        "bundlePath": String(cString: (bundle.bundlePath as NSString).fileSystemRepresentation),
        "executablePath": String(cString: (bundle.executablePath! as NSString).fileSystemRepresentation),
        "frameworksPath": String(cString: (bundle.privateFrameworksPath! as NSString).fileSystemRepresentation),
        "processID": getpid(),
        "bundleID": bundle.bundleIdentifier ?? "",
        "arch": arch,
        "isRosetta": false,
        "buildTime": {
            if let execPath = Bundle.main.executablePath,
               let attrs = try? environmentGet(L).fileSystem.attributesOfItem(atPath: execPath),
               let modDate = attrs.modificationDate {
                let fmt = DateFormatter()
                fmt.dateFormat = "MMM dd yyyy, HH:mm:ss"
                return fmt.string(from: modDate)
            }
            return "Unknown"
        }(),
        "debugBuild": isDebugBuild,
    ]

    lua_pushany(L, appInfo as NSDictionary)
    assert(lua_gettop(L) == baseTop + 1, "push_hammerAppInfo must push exactly one value")
    return 1
}

