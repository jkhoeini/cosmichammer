// MARK: - UTF-8 validation helper

/// Sanitize a byte buffer into valid UTF-8, replacing NULL bytes with the
/// Unicode Empty Set character (U+2205) and invalid sequences with the
/// Unicode Replacement Character (U+FFFD).
private func getValidUTF8(_ src: UnsafePointer<CChar>?, ofLength sourceLength: Int) -> String {
    precondition(sourceLength >= 0, "source length must not be negative")
    guard let src = src, sourceLength > 0 else { return "" }
    let nullChar: [UInt8] = [0xE2, 0x88, 0x85]     // U+2205
    let invalidChar: [UInt8] = [0xEF, 0xBF, 0xBD]  // U+FFFD

    // Rebind CChar pointer to UInt8 for unsigned byte comparisons
    let bytes = UnsafeBufferPointer(start: UnsafeRawPointer(src).assumingMemoryBound(to: UInt8.self),
                                    count: sourceLength)

    var dest = Data()
    dest.reserveCapacity(sourceLength)
    var pos = 0
    while pos < sourceLength {
        let b = bytes[pos]
        if b > 0 && b <= 127 {
            dest.append(b); pos += 1
        } else if b >= 194 && b <= 223 && pos + 1 < sourceLength &&
                    bytes[pos + 1] >= 128 && bytes[pos + 1] <= 191 {
            dest.append(b); dest.append(bytes[pos + 1]); pos += 2
        } else if b >= 224 && b <= 239 && pos + 2 < sourceLength &&
                    bytes[pos + 1] >= 128 && bytes[pos + 1] <= 191 &&
                    bytes[pos + 2] >= 128 && bytes[pos + 2] <= 191 {
            dest.append(b); dest.append(bytes[pos + 1]); dest.append(bytes[pos + 2]); pos += 3
        } else if b >= 240 && b <= 244 && pos + 3 < sourceLength &&
                    bytes[pos + 1] >= 128 && bytes[pos + 1] <= 191 &&
                    bytes[pos + 2] >= 128 && bytes[pos + 2] <= 191 &&
                    bytes[pos + 3] >= 128 && bytes[pos + 3] <= 191 {
            dest.append(b); dest.append(bytes[pos + 1]); dest.append(bytes[pos + 2]); dest.append(bytes[pos + 3]); pos += 4
        } else {
            if b == 0 {
                dest.append(contentsOf: nullChar)
            } else {
                dest.append(contentsOf: invalidChar)
            }
            pos += 1
        }
    }
    return String(data: dest, encoding: .utf8) ?? ""
}

// MARK: - Lua environment lifecycle, high level

/// Create and configure a Lua environment
@_cdecl("MJLuaCreate")
func MJLuaCreate() {
    MJLuaAlloc()
    MJLuaInit()
    os_log(.info, "Created Lua instance")
}

/// Deconfigure and destroy a Lua environment
@_cdecl("MJLuaDestroy")
func MJLuaDestroy() {
    os_log(.info, "Destroying Lua instance")
    MJLuaDeinit()
    MJLuaDealloc()
}

/// Deconfigure and destroy a Lua environment and create its replacement
@_cdecl("MJLuaReplace")
func MJLuaReplace() {
    MJLuaDeinit()
    MJLuaDealloc()
    MJConsoleWindowController.singleton().initializeConsoleColorsAndFont()

    MJLuaAlloc()
    MJLuaInit()
}

// MARK: - Lua environment lifecycle, low level

private func MJLuaAtPanic(_ L: UnsafeMutablePointer<lua_State>?) -> Int32 {
    os_log(.fault, "LUA_AT_PANIC: %{public}s", lua_tostring(L, -1).map { String(cString: $0) } ?? "<nil>")
    if let oldPanicFunction = oldPanicFunction {
        return oldPanicFunction(L)
    }
    return 0
}

/// Create a Lua environment
@_cdecl("MJLuaAlloc")
func MJLuaAlloc() {
    let traceState = CHTrace.signposter.beginInterval("LuaAlloc")
    defer { CHTrace.signposter.endInterval("LuaAlloc", traceState) }

    if MJLuaLogDelegate == nil {
        MJLuaLogDelegate = HSLoggerCreateWithLua(nil)
    }
    var L = lua_getCurrentState()
    if L == nil {
        L = luaL_newstate()
        luaL_openlibs(L)
        let env = createProductionEnvironment()
        environmentAttach(L, env)
        environmentSetGlobal(env)
        lua_setCurrentState(L)
        lua_bumpStateGeneration()
    }
    HSLoggerSetLuaState(MJLuaLogDelegate!, L)
    oldPanicFunction = lua_atpanic(L, MJLuaAtPanic)
}

/// Configure a Lua environment that has already been created
@_cdecl("MJLuaInit")
func MJLuaInit() {
    let traceState = CHTrace.signposter.beginInterval("LuaInit")
    defer { CHTrace.signposter.endInterval("LuaInit", traceState) }

    let L = lua_getCurrentState()!

    registerHSGlobalTable(L)
    installLuaSkinCompatibilityGlobals(L)

    // Register every bundled hs.lib<name> entry point into package.preload before setup.lua runs.
    let extRegState = CHTrace.signposter.beginInterval("RegisterExtensions")
    hsExtensionsRegisterAll(L)
    CHTrace.signposter.endInterval("RegisterExtensions", extRegState)

    guard let setupPath = Bundle.main.path(forResource: "setup", ofType: "lua"),
          let extensionsPath = Bundle.main.path(forResource: "extensions", ofType: nil),
          let docsPath = Bundle.main.path(forResource: "docs", ofType: "json") else {
        terminateWithCorruptInstallationAlert()
        return
    }

    let context = buildBootContext(L, extensionsPath: extensionsPath, docsPath: docsPath)
    let setupState = CHTrace.signposter.beginInterval("RunSetupLua")
    runSetupOrTerminate(L, setupPath: setupPath, context: context)
    CHTrace.signposter.endInterval("RunSetupLua", setupState)
}

