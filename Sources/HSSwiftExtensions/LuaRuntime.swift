// MARK: - Lua boot contract

enum LuaBoot {
    struct Context: Equatable {
        let extensionsPath: String
        let configFileDisplayPath: String
        let configFilePath: String
        let configDir: String
        let dataDir: String
        let docsJSONPath: String
        let hasInitFile: Bool
        let autoloadExtensions: Bool
    }

    struct LifecycleReferences: Equatable {
        let evalFunctionRef: Int32
        let completionsFunctionRef: Int32
    }

    enum Error: Swift.Error, CustomStringConvertible {
        case loadFailed(String)
        case runtimeFailed(String)
        case invalidLifecycle(String)

        var description: String {
            switch self {
            case .loadFailed(let message),
                 .runtimeFailed(let message),
                 .invalidLifecycle(let message):
                return message
            }
        }
    }

    static func runSetup(
        _ L: UnsafeMutablePointer<lua_State>,
        setupPath: String,
        context: Context
    ) throws -> LifecycleReferences {
        precondition(!setupPath.isEmpty, "setup path must not be empty")
        precondition(!context.extensionsPath.isEmpty, "extensions path must not be empty")
        let baseTop = lua_gettop(L)
        let loadResult = luaL_loadfilex(L, (setupPath as NSString).fileSystemRepresentation, nil)
        guard loadResult == LUA_OK else {
            let message = readString(L, at: -1) ?? "(unknown error)"
            lua_settop(L, baseTop)
            throw Error.loadFailed("Unable to load setup.lua: \(message)")
        }

        pushContext(L, context)

        guard lua_pcall(L, 1, 1, 0) == LUA_OK else {
            let message = readString(L, at: -1) ?? "(unknown error)"
            lua_settop(L, baseTop)
            throw Error.runtimeFailed("Error running setup.lua: \(message)")
        }

        guard lua_type(L, -1) == LUA_TTABLE else {
            let actual = typeName(L, at: -1)
            lua_settop(L, baseTop)
            throw Error.invalidLifecycle("setup.lua returned \(actual); expected one lifecycle table")
        }

        let lifecycleIndex = lua_absindex(L, -1)
        lua_getfield(L, lifecycleIndex, "runString")
        lua_getfield(L, lifecycleIndex, "completionsForInputString")

        let runStringType = lua_type(L, -2)
        let completionsType = lua_type(L, -1)
        guard runStringType == LUA_TFUNCTION, completionsType == LUA_TFUNCTION else {
            let message = "setup.lua lifecycle table must contain function fields runString and completionsForInputString; got \(typeName(runStringType)) and \(typeName(completionsType))"
            lua_settop(L, baseTop)
            throw Error.invalidLifecycle(message)
        }

        let completionsRef = luaL_ref(L, LUA_REGISTRYINDEX_VALUE)
        let evalRef = luaL_ref(L, LUA_REGISTRYINDEX_VALUE)
        lua_pop(L, 1)

        assert(evalRef != LUA_NOREF, "evalFunctionRef must be a valid registry reference")
        assert(evalRef != LUA_REFNIL, "evalFunctionRef must not be nil ref")
        assert(completionsRef != LUA_NOREF, "completionsFunctionRef must be a valid registry reference")
        assert(completionsRef != LUA_REFNIL, "completionsFunctionRef must not be nil ref")
        assert(lua_gettop(L) == baseTop, "stack must be balanced after runSetup")

        return LifecycleReferences(
            evalFunctionRef: evalRef,
            completionsFunctionRef: completionsRef
        )
    }

    static func pushContext(_ L: UnsafeMutablePointer<lua_State>, _ context: Context) {
        let baseTop = lua_gettop(L)
        lua_createtable(L, 0, 8)
        setField(L, "extensionsPath", context.extensionsPath)
        setField(L, "configFileDisplayPath", context.configFileDisplayPath)
        setField(L, "configFilePath", context.configFilePath)
        setField(L, "configDir", context.configDir)
        setField(L, "dataDir", context.dataDir)
        setField(L, "docsJSONPath", context.docsJSONPath)
        setField(L, "hasInitFile", context.hasInitFile)
        setField(L, "autoloadExtensions", context.autoloadExtensions)
        assert(lua_gettop(L) == baseTop + 1, "pushContext must leave exactly one table on the stack")
        assert(lua_type(L, -1) == LUA_TTABLE, "pushContext must leave a table on top of the stack")
    }

    private static func setField(_ L: UnsafeMutablePointer<lua_State>, _ name: String, _ value: String) {
        _ = value.withCString { lua_pushstring(L, $0) }
        name.withCString { lua_setfield(L, -2, $0) }
    }

    private static func setField(_ L: UnsafeMutablePointer<lua_State>, _ name: String, _ value: Bool) {
        lua_pushboolean(L, value ? 1 : 0)
        name.withCString { lua_setfield(L, -2, $0) }
    }

    private static func readString(_ L: UnsafeMutablePointer<lua_State>, at index: Int32) -> String? {
        var len: Int = 0
        guard let raw = lua_tolstring(L, index, &len) else { return nil }
        return String(data: Data(bytes: raw, count: len), encoding: .utf8)
            ?? String(cString: raw)
    }

    private static func typeName(_ L: UnsafeMutablePointer<lua_State>, at index: Int32) -> String {
        typeName(lua_type(L, index))
    }

    private static func typeName(_ type: Int32) -> String {
        guard let name = lua_typename(nil, type) else { return "unknown" }
        return String(cString: name)
    }
}

