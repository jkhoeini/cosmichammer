/// Deconfigure a Lua environment that will shortly be destroyed
@_cdecl("MJLuaDeinit")
func MJLuaDeinit() {
    guard let L = lua_getCurrentState() else { return }

    callShutdownCallback(L)
    evalfn = LUA_NOREF
    completionsForWordFn = LUA_NOREF

    HSLoggerSetLuaState(MJLuaLogDelegate as AnyObject, nil)
}

/// Destroy a Lua environment
@_cdecl("MJLuaDealloc")
func MJLuaDealloc() {
    if let L = lua_getCurrentState() {
        environmentClearGlobal()

        // Bump generation BEFORE lua_close so async callbacks (which check
        // generation) bail out, but keep the state pointer alive because
        // synchronous GC finalizers (e.g. HSWebViewWindow.windowWillClose)
        // force-unwrap lua_getCurrentState() before their generation check.
        lua_bumpStateGeneration()

        // Save the Environment pointer from extra-space BEFORE lua_close frees
        // the lua_State memory. GC finalizers during lua_close can still read
        // the environment via the (not-yet-zeroed) extra-space slot.
        let extra = lua_getextraspace(L)!
        let envRaw = extra.load(as: UnsafeMutableRawPointer?.self)

        lua_close(L)

        // NOW nil the state — lua_close is done, no more finalizers running.
        lua_setCurrentState(nil)

        // Release the Environment from our saved pointer — NOT from the
        // now-freed lua_State. This was the crash: environmentDetach(L)
        // called lua_getextraspace on freed memory.
        if let raw = envRaw {
            Unmanaged<Environment>.fromOpaque(raw).release()
        }
    }
}

// MARK: - Run string / completions / get active state

@_cdecl("MJLuaRunString")
func MJLuaRunString(_ command: NSString) -> NSString {
    // Note: command can be empty (valid Lua noop); Swift's type system ensures non-nil.
    guard let L = currentLuaStateForCallback("MJLuaRunString") else { return "" }
    _lua_stackguard_entry(L)

    guard evalfn != LUA_NOREF else {
        os_log(.error, "ERROR: MJLuaRunString called before Lua lifecycle refs are available")
        _lua_stackguard_exit(L)
        return ""
    }

    lua_rawgeti(L, LUA_REGISTRYINDEX_VALUE, lua_Integer(evalfn))
    if !lua_isfunction(L, -1) {
        os_log(.error, "ERROR: MJLuaRunString doesn't seem to have an evalfn")
        if lua_isstring(L, -1) {
            os_log(.error, "evalfn appears to be a string: %{public}s", lua_tostring(L, -1).map { String(cString: $0) } ?? "")
        }
        // Whatever evalfn was, it wasn't a function, so pop it
        lua_pop(L, 1)
        _lua_stackguard_exit(L)
        return ""
    }
    lua_pushstring(L, (command as String).cString(using: .utf8))
    if lua_pcall(L, 1, 1, 0) != LUA_OK {
        if let errorMsg = lua_tostring(L, -1) {
            os_log(.error, "%{public}s", String(cString: errorMsg))
        }
    }

    var len: Int = 0
    let s = lua_tolstring(L, -1, &len)
    var str: NSString
    if let s = s, let converted = String(data: Data(bytes: s, count: len), encoding: .utf8) {
        str = converted as NSString
    } else if let s = s {
        str = getValidUTF8(s, ofLength: len) as NSString
    } else {
        str = ""
    }
    lua_pop(L, 1)

    _lua_stackguard_exit(L)
    return str
}

@_cdecl("MJLuaCompletionsForWord")
func MJLuaCompletionsForWord(_ completionWord: NSString) -> NSArray {
    // Note: completionWord can be empty (prefix matching); Swift's type system ensures non-nil.
    guard let L = currentLuaStateForCallback("MJLuaCompletionsForWord") else { return [] }
    _lua_stackguard_entry(L)

    guard completionsForWordFn != LUA_NOREF else {
        os_log(.error, "ERROR: MJLuaCompletionsForWord called before Lua lifecycle refs are available")
        _lua_stackguard_exit(L)
        return []
    }

    lua_rawgeti(L, LUA_REGISTRYINDEX_VALUE, lua_Integer(completionsForWordFn))
    lua_pushany(L, completionWord)
    if lua_pcall(L, 1, 1, 0) != LUA_OK {
        let err = lua_tostring(L, -1).map { String(cString: $0) } ?? "(unknown)"
        os_log(.error, "MJLuaCompletionsForWord: %{public}s", err)
        lua_pop(L, 1)
        _lua_stackguard_exit(L)
        return []
    }

    let completions = lua_tovalue(L, at: -1) as? [Any] ?? []
    lua_pop(L, 1)
    _lua_stackguard_exit(L)
    return completions as NSArray
}

