private func terminateWithCorruptInstallationAlert() {
    os_log(.fault, "Unable to find boot resources in bundle. Terminating")
    let alert = NSAlert()
    alert.addButton(withTitle: "OK")
    alert.messageText = "Cosmic Hammer installation is corrupted"
    alert.informativeText = "Please re-install Cosmic Hammer"
    alert.alertStyle = .critical
    alert.runModal()
    NSApplication.shared.terminate(nil)
}

private func buildBootContext(_ L: UnsafeMutablePointer<lua_State>, extensionsPath: String, docsPath: String) -> LuaBoot.Context {
    LuaBoot.Context(
        extensionsPath: extensionsPath,
        configFileDisplayPath: MJConfigFileGet() as String,
        configFilePath: MJConfigFileFullPath() as String,
        configDir: MJConfigDir() as String,
        dataDir: XDGPaths.dataHome,
        docsJSONPath: docsPath,
        hasInitFile: environmentGet(L).fileSystem.fileExists(atPath: MJConfigFileFullPath() as String),
        autoloadExtensions: environmentGet(L).settings.bool(forKey: HSAutoLoadExtensions)
    )
}

private func runSetupOrTerminate(_ L: UnsafeMutablePointer<lua_State>, setupPath: String, context: LuaBoot.Context) {
    do {
        let lifecycle = try LuaBoot.runSetup(L, setupPath: setupPath, context: context)
        evalfn = lifecycle.evalFunctionRef
        completionsForWordFn = lifecycle.completionsFunctionRef
        os_log(.default, "BREADCRUMB: setup.lua completed")
    } catch let error as LuaBoot.Error {
        terminateWithInitFailureAlert(error.description)
    } catch {
        terminateWithInitFailureAlert(String(describing: error))
    }
}

private func terminateWithInitFailureAlert(_ message: String) {
    os_log(.error, "%{public}s", message)
    let alert = NSAlert()
    alert.addButton(withTitle: "OK")
    alert.messageText = "Cosmic Hammer initialization failed"
    alert.informativeText = message
    alert.alertStyle = .critical
    alert.runModal()
    NSApplication.shared.terminate(nil)
}

// MARK: - Callbacks

private func currentLuaStateForCallback(_ callbackName: String) -> UnsafeMutablePointer<lua_State>? {
    guard let L = lua_getCurrentState() else {
        os_log(.debug, "Skipping %{public}s callback because Lua state is not available", callbackName)
        return nil
    }
    return L
}

/// Accessibility State Callback
@_cdecl("callAccessibilityStateCallback")
func callAccessibilityStateCallback() {
    guard let L = currentLuaStateForCallback("hs.accessibilityStateCallback") else { return }
    _lua_stackguard_entry(L)

    lua_getglobal(L, "hs")
    lua_getfield(L, -1, "accessibilityStateCallback")

    if lua_type(L, -1) == LUA_TNIL {
        // There is no callback set, so just pop the callback and carry on
        lua_pop(L, 1)
    } else {
        if lua_pcall(L, 0, 0, 0) != LUA_OK {
            let err = lua_tostring(L, -1).map { String(cString: $0) } ?? "(unknown)"
            os_log(.error, "hs.callAccessibilityStateCallback: %{public}s", err)
            lua_pop(L, 1)
        }
    }

    // Pop the hs global off the stack
    lua_pop(L, 1)
    _lua_stackguard_exit(L)
}

